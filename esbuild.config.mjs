import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFileSync } from "node:fs";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/* Cropper.js
${readFileSync(new URL('./node_modules/cropperjs/LICENSE', import.meta.url), 'utf-8')}
*/
`;

const prod = (process.argv[2] === 'production');

const cssOptions = {
	entryPoints: ['src/styles/index.css'], bundle: true, outfile: 'styles.css',
	logLevel: 'info', legalComments: 'inline',
};

const options = {
	banner: {
		js: banner,
	},
	entryPoints: ['src/plugin.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules, ...builtinModules.map(name => 'node:' + name)],
	format: 'cjs',
	target: 'es2018',
	logLevel: "info",
	sourcemap: false,
	treeShaking: true,
	minify: prod,
	outfile: 'main.js',
	loader: {
		'.css': 'text',
		'.md': 'text',
		'.jpg': 'dataurl',
	},
	plugins: [{
		name: 'normalize-text-assets',
		setup(build) {
			build.onLoad({ filter: /\.(css|md)$/ }, args => ({
				contents: readFileSync(args.path, 'utf8').replace(/\r\n?/g, '\n'), loader: 'text',
			}));
		},
	}],
	metafile: false,
};

const footer = {
	js: 'module.exports = module.exports && module.exports.default || module.exports;',
};

if (prod) {
	try {
		await esbuild.build({ ...options, footer });
		await esbuild.build(cssOptions);
	} catch (e) {
		console.error(e);
		process.exit(1);
	}
} else {
	try {
		const context = await esbuild.context({ ...options, footer });
		const cssContext = await esbuild.context(cssOptions);
		await context.watch();
		await cssContext.watch();
	} catch (e) {
		console.error(e);
		process.exit(1);
	}
}
